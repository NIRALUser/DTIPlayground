"""O1 (learning curve) and O3 (finer age bins): table, figure and macros from cache/o1o3_results.csv,
cache/o1o3_scans.csv and the training-set sizes in cache/o1o3.log (written by o1_o3.py, which saves after every seed).
Writes tables/o1o3.tex, tables/macros_o1o3.tex, figures/fig_o1o3.pdf."""
import os
import re

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import common as C  # noqa: E402

MAC = []
FR = ["25%", "50%", "75%", "100%"]


def mac(k, v):
    MAC.append(C.macro(k, v))


def main():
    R = pd.read_csv(C.CACHE + "/o1o3_results.csv")
    S = pd.read_csv(C.CACHE + "/o1o3_scans.csv")
    seeds = sorted(R.seed.unique())
    # training scans per fraction (mean over the folds of the finished seeds)
    n = {}
    for line in open(C.CACHE + "/o1o3.log"):
        m = re.match(r"^(\d+) (\d+) (O1 (\d+)%|O3 fine bins) (\d+) training scans", line)
        if m and int(m.group(1)) in seeds:
            key = (m.group(4) + "%") if m.group(4) else "fine"
            n.setdefault(key, []).append(int(m.group(5)))
    ntr = {k: np.mean(v) for k, v in n.items()}
    mac("oOneSeeds", str(len(seeds)))
    mac("oOneScans", str(int(S[S.group == "4pat"].groupby("seed").scan.nunique().sum())))
    m = R.groupby("setting").mean(numeric_only=True)
    rows = []
    for f in FR:
        for meth in ["PPCA", "PPCA + kNN"]:
            rows.append(("O1 {}: {}".format(f, meth), f, meth))
    for meth in ["norm alone", "PPCA", "PPCA + kNN"]:
        rows.append(("O3 fine bins: {}".format(meth), "fine", meth))
    ref = {meth: S[S.setting == "O1 100%: {}".format(meth)] for meth in ["PPCA", "PPCA + kNN"]}
    lines = [r"\begin{tabular}{llrcccccc}", r"\toprule",
             r"Norm and PPCA from & Method & Training scans & Overall & Gap & End & Whole & Region & "
             r"Whole: paired vs 100\% \\", r"\midrule"]
    for lab, f, meth in rows:
        r = m.loc[lab]
        pair = "--"
        if meth in ref and f != "100%":
            a = ref[meth][ref[meth].group == "whole profile"][["scan", "seed", "r"]]
            b = S[(S.setting == lab) & (S.group == "whole profile")][["scan", "seed", "r"]]
            p = C.paired(a, b)
            pair = "{:.3f} [{:.3f}, {:.3f}]".format(p["ratio"], p["blo"], p["bhi"])
            tag = {"25%": "Q", "50%": "H", "75%": "T", "fine": "F"}[f] + ("Knn" if meth == "PPCA + kNN" else "Ppca")
            mac("oPair" + tag, "{:.3f}".format(p["ratio"]))
            mac("oPair" + tag + "Ci", "{:.3f}--{:.3f}".format(p["blo"], p["bhi"]))
        flab = {"fine": "7 finer age bins"}.get(f, "{} of training subjects".format(f.replace("%", r"\%")))
        lines.append(r"{} & {} & {:.0f} & {:.3f} & {:.3f} & {:.3f} & {:.3f} & {:.3f} & {} \\".format(
            flab, meth, ntr.get(f, np.nan), r.overall, r.gap, r["end gap"], r["whole profile"], r.region, pair))
        tag = {"25%": "Q", "50%": "H", "75%": "T", "100%": "A", "fine": "F"}[f] + \
            {"PPCA": "Ppca", "PPCA + kNN": "Knn", "norm alone": "Norm"}[meth]
        mac("o" + tag, "{:.3f}".format(r.overall))
        mac("o" + tag + "Whole", "{:.3f}".format(r["whole profile"]))
        if f == "100%" or meth == "PPCA":
            pass
    for f, t in [("25%", "Q"), ("50%", "H"), ("75%", "T"), ("100%", "A")]:
        mac("oN" + t, "{:.0f}".format(ntr.get(f, np.nan)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    C.write_tex("o1o3.tex", "\n".join(lines) + "\n")
    with open(C.TABLES + "/macros_o1o3.tex", "w") as fh:
        fh.write("% generated by scripts/o1o3_tables.py\n")
        fh.writelines(MAC)
    # figure
    plt.rcParams.update({"font.size": 7.5, "axes.labelsize": 7.5, "xtick.labelsize": 6.5, "ytick.labelsize": 6.5,
                         "legend.fontsize": 6.5, "font.family": "DejaVu Sans", "pdf.fonttype": 42})
    fig, axs = plt.subplots(1, 2, figsize=(5.6, 2.2), gridspec_kw=dict(wspace=0.35))
    for ax, col, title in [(axs[0], "whole profile", "(a) Whole profiles"), (axs[1], "overall", "(b) Overall")]:
        for meth, c in [("PPCA", C.OI["orange"]), ("PPCA + kNN", C.OI["blue"])]:
            x = [ntr[f] for f in FR]
            y = [m.loc["O1 {}: {}".format(f, meth), col] for f in FR]
            ax.plot(x, y, marker="o", color=c, label=meth)
        ax.set_xlabel("Training scans (norm and PPCA)")
        ax.set_title(title, loc="left", fontsize=7.5)
        ax.grid(axis="y", color="#d9d9d9", lw=0.4)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    axs[0].set_ylabel("RMSE / RMSE of the age-bin mean")
    axs[0].legend(frameon=False, fontsize=6)
    fig.savefig(C.FIGURES + "/fig_o1o3.pdf", bbox_inches="tight")
    fig.savefig(C.FIGURES + "/fig_o1o3.png", bbox_inches="tight", dpi=200)
    print("".join(MAC))


if __name__ == "__main__":
    main()
