"""Tables, macros and figure of the real-mask pass by donor load (round-2 review, N1/R1), from cache/realmask_*.csv
(realmask.py).

  realmask_scope.tex   E1 and E3: real-mask score of the dump settings with all donors and with donors the tool would
                       impute (at most --max-missing-tracts 0.5 of their tracts missing)
  realmask_load.tex    the same by donor load (missing tracts of the donor) and the share of the cells
  fig_realmask         score against the share of the scan's locations hidden
  macros_realmask.tex  numbers of the text (prefix rm)
Scoring as the paper: per (metric, age bin) RMSE ratio to the age-bin mean on all hidden cells of the selection, mean
over metrics and age bins, then over seeds. Per-scan paired contrasts as common.paired, on the selected passes.
"""
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import common as C  # noqa: E402

SET = [("age-bin mean", "Age-bin mean"), ("PPCA + kNN", "PPCA + $k$NN"), ("PPCA + SIREN", "PPCA + SIREN"),
       ("transformer", "Transformer alone"), ("fixed 0.25/0.75", "Fixed blend (SIREN base)"),
       ("table (shipped)", "Shipped table (released default)"),
       ("kNN base, table (shipped)", "Shipped table ($k$NN base)"),
       ("table (cross-fitted)", "Table refitted on the cohort (cross-fitted)")]
LOAD = [(1, 1, "1"), (2, 5, "2--5"), (6, 15, "6--15"), (16, 34, "16--34"), (35, 999, "$\\geq$35")]
SHARE = [(0, 0.05, "<5"), (0.05, 0.1, "5--10"), (0.1, 0.25, "10--25"), (0.25, 0.5, "25--50"), (0.5, 1.01, ">50")]
SHARE_TXT = ["<5", "5-10", "10-25", "25-50", ">50"]
MAXSHARE = 0.5
TEX = []


def mac(name, value):
    TEX.append(C.macro("rm" + name, value))


def f3(x):
    return "--" if x is None or not np.isfinite(x) else "{:.3f}".format(x)


def read(ds):
    p, s = ["{}/realmask_{}_{}.csv".format(C.CACHE, ds, k) for k in ("passes", "sums")]
    if not (os.path.isfile(p) and os.path.isfile(s)):
        return None, None
    P = pd.read_csv(p)
    S = pd.read_csv(s).merge(P[["seed", "scan", "k", "donor_missing", "donor_share", "share_hidden"]],
                             on=["seed", "scan", "k"])
    return P, S


def score(S, setting):
    x = S[S.setting == setting]
    if not len(x):
        return np.nan
    a = x.groupby(["seed", "metric", "age_bin"])[["e2", "r2"]].sum()
    r = np.sqrt(a.e2 / a.r2).groupby(level="seed").mean()
    return r.mean()


def scans(S, setting):
    x = S[S.setting == setting].groupby(["seed", "scan", "metric"])[["e2", "r2"]].sum()
    x = x[x.r2 > 0]
    r = np.sqrt(x.e2 / x.r2).groupby(level=["seed", "scan"]).mean().rename("r").reset_index()
    r["scan"] = r.scan.str.replace(r"#\d+$", "", regex=True)
    return r


def main():
    data = {ds: read(ds) for ds in ("e1", "e3")}
    if all(v[0] is None for v in data.values()):
        print("no realmask caches")
        return
    TEX.append("% generated by scripts/realmask_tables.py\n")
    # passes and load
    for ds, (P, S) in data.items():
        if P is None:
            continue
        tag = {"e1": "One", "e3": "Three"}[ds]
        mac(tag + "Passes", "{:,}".format(len(P)))
        mac(tag + "HiddenMedian", "{:.0f}".format(P.hidden_locs.median()))
        mac(tag + "HiddenMean", "{:.0f}".format(P.hidden_locs.mean()))
        out = P.donor_share > MAXSHARE
        mac(tag + "OutPasses", "{:,}".format(int(out.sum())))
        mac(tag + "OutPassShare", "{:.1f}".format(100 * out.mean()))
        cells = S[S.setting == "age-bin mean"]
        mac(tag + "OutCellShare", "{:.0f}".format(100 * cells.n[cells.donor_share > MAXSHARE].sum() / cells.n.sum()))
        mac(tag + "MaxHidden", "{:.0f}".format(100 * P.share_hidden.max()))
        mac(tag + "OverHalfHidden", "{:,}".format(int((P.share_hidden > 0.5).sum())))
        mac(tag + "Unique", "{:.0f}".format(100 * (P.n_match == 1).mean()))
        mac(tag + "Ambiguous", "{:,}".format(int((P.donor_missing != P.donor_missing_max).sum())))
    # scope table
    lines = [r"\begin{tabular}{lcccc}", r"\toprule",
             r" & \multicolumn{2}{c}{BCP, untouched subjects (E1)} & \multicolumn{2}{c}{HBCD (E3)} \\",
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
             r"Setting & all donors & donors $\leq$50\% tracts missing & all donors & donors $\leq$50\% tracts missing \\",
             r"\midrule"]
    res = {}
    for key, lab in SET:
        row = [lab]
        for ds in ("e1", "e3"):
            P, S = data[ds]
            for sel in ("all", "in"):
                v = np.nan
                if S is not None:
                    x = S if sel == "all" else S[S.donor_share <= MAXSHARE]
                    v = score(x, key)
                res[(ds, sel, key)] = v
                row.append(f3(v))
        lines.append(" & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    C.write_tex("realmask_scope.tex", "\n".join(lines) + "\n")
    short = {"age-bin mean": "Mean", "PPCA + kNN": "Knn", "PPCA + SIREN": "Def", "transformer": "Tf",
             "fixed 0.25/0.75": "Fixed", "table (shipped)": "Final", "kNN base, table (shipped)": "FinalKnn",
             "table (cross-fitted)": "Refit"}
    for (ds, sel, key), v in res.items():
        mac({"e1": "One", "e3": "Three"}[ds] + short[key] + ("All" if sel == "all" else "In"), f3(v))
    # paired, in scope
    pairs = [("FinalVsDef", "PPCA + SIREN", "table (shipped)"), ("KnnVsDef", "PPCA + SIREN", "PPCA + kNN"),
             ("TfVsFinal", "table (shipped)", "transformer"), ("RefitVsTf", "transformer", "table (cross-fitted)")]
    for ds in ("e1", "e3"):
        P, S = data[ds]
        if S is None:
            continue
        x = S[S.donor_share <= MAXSHARE]
        for name, a, b in pairs:
            r = C.paired(scans(x, a), scans(x, b))
            t = {"e1": "One", "e3": "Three"}[ds] + name
            mac(t, f3(r["ratio"]))
            mac(t + "Ci", "{:.3f}--{:.3f}".format(r["blo"], r["bhi"]))
    # per scan against the age-bin mean (round-3 review): on the smallest masks (< 5% hidden) and on all passes in scope
    for ds in ("e1", "e3"):
        P, S = data[ds]
        if S is None:
            continue
        t = {"e1": "One", "e3": "Three"}[ds]
        for sel, x in (("Small", S[S.share_hidden < 0.05]), ("In", S[S.donor_share <= MAXSHARE])):
            base = scans(x, "age-bin mean")
            for key in ("PPCA + SIREN", "transformer", "table (shipped)"):
                r = C.paired(base, scans(x, key))
                mac(t + "Scan" + sel + short[key], f3(r["ratio"]))
                mac(t + "Scan" + sel + short[key] + "Ci", "{:.3f}--{:.3f}".format(r["blo"], r["bhi"]))
                mac(t + "Scan" + sel + short[key] + "Better", "{:.0f}".format(100 * r["better"]))
            mac(t + "Scan" + sel + "N", "{:,}".format(int(((x.setting == "age-bin mean")).sum() and
                                                          x[x.setting == "age-bin mean"].groupby(["seed", "k", "scan"]).ngroups)))
        for i, (lo, hi, _) in enumerate(SHARE):
            mac(t + "SharePasses" + "ABCDE"[i], "{:,}".format(int(((P.share_hidden >= lo) & (P.share_hidden < hi)).sum())))
    # by donor load and by hidden share
    keys = ["PPCA + kNN", "PPCA + SIREN", "transformer", "table (shipped)", "table (cross-fitted)"]
    labs = dict(SET)
    lines = [r"\begin{tabular}{llr" + "c" * len(keys) + "}", r"\toprule",
             "Cohort & Donor missing tracts & Cells (\\%) & " + " & ".join(labs[k] for k in keys) + r" \\",
             r"\midrule"]
    curves = {}
    for ds in ("e1", "e3"):
        P, S = data[ds]
        if S is None:
            continue
        base = S[S.setting == "age-bin mean"]
        tot = base.n.sum()
        for i, (lo, hi, lab) in enumerate(LOAD):
            x = S[(S.donor_missing >= lo) & (S.donor_missing <= hi)]
            share = 100 * base.n[(base.donor_missing >= lo) & (base.donor_missing <= hi)].sum() / tot
            vals = [score(x, k) for k in keys]
            lines.append(" & ".join([("BCP (E1)" if ds == "e1" else "HBCD (E3)") if i == 0 else "", lab,
                                     "{:.0f}".format(share)] + [f3(v) for v in vals]) + r" \\")
            if ds == "e3":
                for k, v in zip(keys, vals):
                    mac("ThreeLoad" + "ABCDE"[i] + short[k], f3(v))
                mac("ThreeLoad" + "ABCDE"[i] + "Cells", "{:.0f}".format(share))
        if ds == "e1":
            lines.append(r"\midrule")
        for k in ["PPCA + SIREN", "PPCA + kNN", "transformer", "table (shipped)"]:
            ys, ns = [], []
            for lo, hi, _ in SHARE:
                x = S[(S.share_hidden >= lo) & (S.share_hidden < hi)]
                ys.append(score(x, k))
                ns.append(int(P[(P.share_hidden >= lo) & (P.share_hidden < hi)].shape[0]))
            curves[(ds, k)] = (ys, ns)
        for i, (lo, hi, _) in enumerate(SHARE):
            t = {"e1": "One", "e3": "Three"}[ds]
            for k in ["PPCA + SIREN", "transformer", "table (shipped)"]:
                mac(t + "Share" + "ABCDE"[i] + short[k], f3(curves[(ds, k)][0][i]))
    lines += [r"\bottomrule", r"\end{tabular}"]
    C.write_tex("realmask_load.tex", "\n".join(lines) + "\n")
    C.write_tex("macros_realmask.tex", "".join(TEX))
    # figure
    plt.rcParams.update({"font.size": 7.5, "axes.labelsize": 7.5, "xtick.labelsize": 6.5, "ytick.labelsize": 6.5,
                         "legend.fontsize": 6.5, "font.family": "DejaVu Sans", "pdf.fonttype": 42})
    fig, axs = plt.subplots(1, 2, figsize=(6.2, 2.3), sharey=True, gridspec_kw=dict(wspace=0.08))
    col = {"PPCA + SIREN": C.OI["orange"], "PPCA + kNN": C.OI["sky"], "transformer": C.OI["red"],
           "table (shipped)": C.OI["black"]}
    lab = {"PPCA + SIREN": "PPCA + SIREN", "PPCA + kNN": "PPCA + kNN", "transformer": "Transformer alone",
           "table (shipped)": "Released default"}
    for ax, ds, title in zip(axs, ("e1", "e3"), ("(a) BCP, untouched subjects (E1)", "(b) HBCD (E3)")):
        xs = np.arange(len(SHARE))
        for k in col:
            if (ds, k) not in curves:
                continue
            ys, ns = curves[(ds, k)]
            ax.plot(xs, ys, "-o", color=col[k], ms=3.5, lw=1.2, label=lab[k])
        if (ds, "PPCA + SIREN") in curves:
            ns = curves[(ds, "PPCA + SIREN")][1]
            ax.set_xticks(xs)
            ax.set_xticklabels(["{}\n(n={})".format(s, n) for s, n in zip(SHARE_TXT, ns)])
        ax.axhline(1.0, color="0.4", lw=0.8, ls="--")
        ax.set_title(title, fontsize=7.5, loc="left")
        ax.set_xlabel("Locations of the scan hidden (%; passes)")
        top = np.nanmax([v for (d, _), (ys, _) in curves.items() for v in ys])
        ax.set_ylim(0, max(1.05, top * 1.05))
        ax.grid(axis="y", color="0.9")
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axs[0].set_ylabel("RMSE / RMSE of the age-bin mean")
    axs[0].legend(frameon=False, loc="lower left")
    fig.savefig(C.FIGURES + "/fig_realmask.pdf", bbox_inches="tight")
    fig.savefig(C.FIGURES + "/fig_realmask.png", dpi=200, bbox_inches="tight")


if __name__ == "__main__":
    main()
